export type Lang = (typeof LANGS)[number]["id"];

const RTL: Lang[] = ["ar", "ur"];

export function isLang(value: string | null | undefined): value is Lang {
  return LANGS.some((item) => item.id === value);
}

export function isRtl(lang: Lang) {
  return RTL.includes(lang);
}

export function detectLang(code?: string | null): Lang {
  const raw = String(code || "")
    .toLowerCase()
    .replace("_", "-");
  const short = raw.split("-")[0];
  if (short === "fil") return "tl";
  if (short === "kh") return "km";
  if (isLang(raw)) return raw;
  if (isLang(short)) return short;
  return "en";
}

